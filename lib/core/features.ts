/** 12운성 중 기운이 오른 자리 */
const ALIVE = ["장생", "관대", "건록", "제왕"];

/** 십신 갈래의 길흉 — 이 엔진에서 가장 중요한 자리다.
 *
 *  명리는 십신의 **양**으로 성향을 읽지 않는다. 그 십신이 이 명식에 용신인지
 *  기신인지로 읽는다. 같은 재성 3.0이라도
 *    용신이면  현실을 다루는 힘이 실제로 살아 있다
 *    기신이면  돈과 사람에 시달린다 — 많아서 좋은 게 아니라 많아서 힘들다
 *  양만 보면 이 둘이 같은 점수를 받는다. 사주 앱들이 십신을 용신·기신 렌즈로
 *  읽는 것이 이 때문이다.
 *
 *  다만 세게 걸면 안 된다. 명리에서 기신 십신은 "그 성향이 없다"가 아니라
 *  "그 방면에서 고생한다"는 뜻이다. 식상이 기신으로 3.4면 표현을 안 하는 게
 *  아니라, 표현을 많이 하되 그게 자기를 소모시킨다. 레이더는 "어떤 사람인가"를
 *  보여 주는 자리지 "그게 이로운가"를 보여 주는 자리가 아니다. 이로운지 아닌지는
 *  본문 규칙이 "기신이라 시달린다"고 따로 말한다.
 *
 *  용신 1.15 · 희신 1.07 · 한신 0.95 · 기신 0.85. 방향만 주고 크기는 남긴다. */
const GROUPS = ["비겁", "식상", "재성", "관성", "인성"] as const;
type Group = (typeof GROUPS)[number];

/** 십신 갈래 → 오행. 일간을 기준으로 정해진다. */
const groupEl = (dayEl: number, k: Group): number =>
  ({ 비겁: dayEl, 식상: (dayEl + 1) % 5, 재성: (dayEl + 2) % 5, 관성: (dayEl + 3) % 5, 인성: (dayEl + 4) % 5 })[k];

/** 십신 이름 → 갈래 */
const groupOfGod = (g: string): Group | null =>
  g === "비견" || g === "겁재" ? "비겁"
  : g === "식신" || g === "상관" ? "식상"
  : g === "편재" || g === "정재" ? "재성"
  : g === "편관" || g === "정관" ? "관성"
  : g === "편인" || g === "정인" ? "인성"
  : null;

export function favorOf(a: Analysis, k: Group): number {
  const e = groupEl(a.dayEl, k);
  if (e === a.useEl) return 1.15;
  if (e === a.helpEl) return 1.07;
  if (e === a.avoidEl) return 0.85;
  return 0.95;
}

export function extractFeatures(a: Analysis): Features {
  // 시간을 모르면 시주가 없어 여덟 글자 중 여섯 자만 잡힌다. 십신 무게가 통째로
  // 작게 나와서, 개수나 무게를 재는 특성이 전부 낮은 쪽으로 쏠린다. 시간을 아는
  // 사람과 같은 눈금에 놓으려면 빠진 만큼 되돌려 줘야 한다.
  // (시주 자체의 정보는 복구할 수 없다 — 눈금만 맞추는 보정이다.)
  const noHour = !a.pillars.시;
  const lift = noHour ? 8 / 6 : 1;
  const raw = Object.fromEntries(
    (["비겁", "식상", "재성", "관성", "인성"] as const).map((k) => [k, a.groupWeight[k] * lift]),
  ) as Record<Group, number>;
  // 효용 무게 — 그 십신을 실제로 쓸 수 있는 양. 아래 특성은 전부 이걸 쓴다.
  // 공망(空亡) — 그 자리가 비어 있다고 보는 곳이다. 글자는 있는데 힘을 못 쓴다.
  // 년지 정인이 공망이면 인성이 있어도 실제로는 덜 작동한다. 그 자리의 십신을 깎는다.
  const voidPos = a.sinsal.find((x) => x.name === "공망")?.where ?? [];
  for (const pos of voidPos) {
    const t = a.tenGods.find((x) => x.pos === pos);
    if (!t) continue;
    const k = groupOfGod(t.branch as string);
    if (k) raw[k] = Math.max(0, raw[k] - 0.55);
  }

  const g = Object.fromEntries(GROUPS.map((k) => [k, raw[k] * favorOf(a, k)])) as Record<Group, number>;
  /** 인성이 기신일 때만 의존으로 본다. 용신이면 기대는 게 아니라 내 뿌리다. */
  const 인성기신 = favorOf(a, "인성") < 0.7;
  const el = a.elementWeight;
  const gods = a.tenGods.flatMap((t) => [t.stem, t.branch]) as string[];
  const has = (n: string) => a.sinsal.some((s) => s.name === n);
  const cnt = (...n: string[]) => gods.filter((x) => n.includes(x)).length;
  const dayStage = a.twelve.find((t) => t.pos === "일")?.stage ?? "제왕";
  const dayAlive = ALIVE.includes(dayStage);
  const rel = (k: Analysis["relations"][number]["kind"]) => a.relations.filter((r) => r.kind === k).length;

  // ── 생극제화 — 십신끼리의 상호작용. 명리에서 실제로 이름이 붙은 구조들.
  const 식상생재 = g.식상 >= 1 && g.재성 >= 1;          // 만들어서 판다
  const 관인상생 = g.관성 >= 1 && g.인성 >= 1;          // 자리가 배움을 부른다
  const 재생관 = g.재성 >= 1 && g.관성 >= 1;            // 재물이 자리를 만든다
  const 상관견관 = cnt("상관") > 0 && cnt("정관") > 0;  // 상관이 정관을 친다 — 규범과 충돌
  const 군겁쟁재 = g.비겁 >= 2 && g.재성 < 1;           // 나눌 것보다 나눌 사람이 많다
  const 인다신왕 = g.인성 >= 2.5 && g.식상 < 1;         // 받아들이기만 하고 못 내놓는다

  const 감당력 = a.strengthScore;
  // ⚠️ 아래 특성에는 강약(감당력)을 섞지 않는다.
  //    감당력은 3층(발현력)에서 능력별 민감도와 함께 한 번만 건다.
  //    1층에도 넣으면 이중으로 걸려서, 감당에 둔감해야 할 능력까지 같이 눌린다.

  // ── 일지(日支) — 명리에서 가장 크게 보는 자리 중 하나다.
  // 배우자궁이자 이 사람이 딛고 선 자리라, 여기 앉은 십신의 성질이 곧 그 사람의
  // 축이 된다. 정(正) 계열(정인·정관·정재)이 앉으면 심지가 곧고, 그것이 용신이면
  // 그 성질이 실제로 살아 움직인다. 십신 총량만 보면 이 자리가 통째로 묻힌다.
  const 일지십신 = a.tenGods.find((t) => t.pos === "일")?.branch ?? "";
  const 일지정계열 = ["정인", "정관", "정재"].includes(일지십신 as string);
  const 일지오행 = a.pillars.일 ? BRANCH_EL[a.pillars.일.branch] : -1;
  const 일지용신 = 일지오행 === a.useEl || 일지오행 === a.helpEl;
  const 심지 = (일지정계열 ? 30 : 0) + (일지용신 ? 22 : 0);

  // ── 인극식상(印剋食傷) — 인성은 식상을 극한다.
  // 표현하려는 힘을 안에서 눌러 세운다. 인성이 용신이면 더 강하게 누른다.
  const 인극 = w100(raw.인성) * (인성기신 ? 0.25 : 0.45);
  const avg = el.reduce((s, v) => s + v, 0) / 5;
  const sd = Math.sqrt(el.reduce((s, v) => s + (v - avg) ** 2, 0) / 5);
  const 균형도 = clamp(100 - sd * 45);

  return {
    표현성: clamp(w100(g.식상) - 인극 + (has("문창귀인") ? 8 : 0) - (인다신왕 ? 12 : 0)),
    // 사교의 핵심은 식상이다. 밖으로 내보내는 힘이 사람과 닿게 한다.
    // 비겁을 넣었었는데, 비겁은 또래이자 경쟁이라 사교성으로 직결되지 않는다.
    대인접근성: clamp(w100(g.식상) * 0.45 + w100(g.재성) * 0.35 + (has("도화") ? 15 : 0) - (has("화개") ? 10 : 0)),
    자기주도: clamp(w100(g.비겁) * 0.7 + n100(cnt("비견", "겁재"), 3) * 0.3),
    관계확장: clamp(w100(g.재성) * 0.6 + (has("역마") ? 14 : 0) + (has("천을귀인") ? 10 : 0) - (군겁쟁재 ? 12 : 0)),
    // 정서개방 — 식상에 화 기운을 더했었는데, 일간에 따라 화가 곧 식상인 경우가 있어
    // 같은 것을 두 번 세고 있었다(을목에게 화는 식상이다). 화 항을 빼고,
    // 명리가 실제로 가르는 자리를 쓴다.
    //   상관  튀고 발산하는 표현 · 식신  온건하고 안으로 고른 표현
    //   양간  밖으로 · 음간  안으로
    정서개방: clamp(
      w100(g.식상) * 0.5
      + n100(cnt("상관"), 2) * 0.3
      - n100(cnt("식신"), 2) * 0.1
      + (a.dayStem % 2 === 0 ? 12 : -8)
      - 인극 * 0.5,
    ),

    책임성: clamp(w100(g.관성) + (재생관 ? 8 : 0)),
    일관성: clamp(n100(cnt("정관", "정재", "정인"), 5) * 0.5 + 균형도 * 0.25 + 심지 * 0.8 - (상관견관 ? 15 : 0)),
    약속이행: clamp(n100(cnt("정관"), 3) * 0.6 + 심지 * 0.8 - (상관견관 ? 10 : 0)),
    안정성: clamp(w100(g.인성) * 0.35 + w100(el[2], 3) * 0.25 + n100(rel("육합") + rel("삼합"), 3) * 0.2 + 심지 * 0.6),
    관계지속성: clamp((dayAlive ? 62 : 40) + n100(rel("육합"), 2) * 0.3 - rel("충") * 10),

    현실감각: clamp(w100(g.재성)),
    실행력: clamp(w100(g.재성) * 0.55 + w100(g.식상) * 0.2 + (식상생재 ? 25 : 0)),
    자기통제: clamp(w100(g.관성) * 0.5 + w100(g.인성) * 0.3 + (관인상생 ? 15 : 0)),
    지속성: clamp(w100(el[2], 3) * 0.35 + n100(cnt("정관", "정재"), 4) * 0.35 + (dayAlive ? 25 : 8)),
    의사결정력: clamp(w100(g.비겁) * 0.45 + w100(g.관성) * 0.3 + (일지정계열 ? 25 : 10)),

    // 인성이 기신일 때만 의존이다. 용신 인성은 자기를 떠받치는 뿌리라 의존이 아니다.
    외부의존도: clamp((인성기신 ? w100(raw.인성) * 0.7 : 0) + w100(raw.인성) * 0.25),
    // 자율성 — 나를 규율하는 것(관성)과 나를 돌보는 것(인성)이 없을수록
    // 혼자 결정하고 혼자 감당하게 된다. 비겁까지 얇으면 기댈 또래도 없다.
    자율성: clamp(100 - w100(raw.관성) * 0.45 - (인성기신 ? 0 : w100(raw.인성) * 0.2) - w100(raw.비겁) * 0.2),
    감당력,
    균형도,
    구조안정: clamp(gyeokScore(a)),
    통로개방: clamp(w100(g.식상 + g.관성, 5) * 0.7 + (상관견관 ? 0 : 20) + (인다신왕 ? -15 : 10)),
  };
}

/** 격국이 제구실을 하는가 — 그 격이 필요로 하는 십신(guard)이 실제로 있는지.
 *  명리에서 격은 성격(成格)과 파격(破格)으로 갈린다. 재료가 있어야 격이 산다. */
function gyeokScore(a: Analysis): number {
  const g = a.groupWeight;
  const need: Record<string, keyof typeof g> = {
    정재격: "관성", 편재격: "비겁", 정관격: "재성", 편관격: "인성",
    식신격: "재성", 상관격: "재성", 정인격: "관성", 편인격: "재성",
    건록격: "재성", 양인격: "관성", 월겁격: "관성",
  };
  const k = need[a.gyeok.name];
  if (!k) return 55;
  const have = g[k];
  return 40 + Math.min(45, have * 18);
}
