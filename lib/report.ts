export function sectionFallback(ctx: Ctx, q: string, v: string): string {
  const { me, pt, c: category, input } = ctx;
  if (category.id === "love-life") return joinParas(loveLife(q, me, input.name ?? "", v));
  if (category.id === "love-compatibility" && pt) return joinParas(compat(q, me, pt, input.name ?? "", input.partnerName ?? "", v));
  if (category.id === "love-reunion" && pt) return joinParas(reunion(q, me, pt, input.name ?? "", input.partnerName ?? "", v));
  if (category.id === "life-overview") return joinParas(lifeOverview(q, me, input.name ?? "", v));
  return joinParas(light(category, q, me, v));
}

/* ───────────────────── 조립 ───────────────────── */

export function generateReport(input: ReportInput): Report | null {
  const category = categories.find((c) => c.id === input.categoryId);
  if (!category) return null;
  const me = computeChart(input.me);
  const pt = input.partner ? computeChart(input.partner) : undefined;
  const ctx: Ctx = { me, pt, c: category, input };
  const vals = values(ctx);
  const who = input.name ? `${input.name} 님` : "당신";
  const pWho = input.partnerName ? `${input.partnerName} 님` : "상대방";

  // 리포트 한 부 전체에서 "다른 각도" 앵글이 겹치지 않도록 쓰인 인덱스를 누적한다.
  // 문항별로만 중복을 막던 시절엔 궁합 14문항에서 같은 문단이 대여섯 번씩 반복됐다.
  const ledger = new Set<number>();
  const ledgerP = new Set<number>();

  const sections: Section[] = category.questions.map((q, qi) => {
    const val = vals[q] ?? { v: "" };
    const stat = category.previewStats?.find((s) => s.label === q);
    // 접미사가 조사로 시작하면 값의 받침에 맞춘다. 값은 명식에서 나오므로 사람마다
    // 형태가 다르다("2026년 전후" / "35" / "오래"). 조사를 데이터에 박아 두면
    // "전후이 고비예요" 같은 문장이 그대로 나간다.
    const tail = fixJosa(stat?.suffix ?? "", val.v);
    const headline = !stat
      ? `${q} — ${val.v}`
      : stat.subject === "shared"
        ? `${stat.prefix}${val.v}${tail}`
        : `${stat.subject === "partner" ? pWho : who}의 ${stat.prefix}${val.v}${tail}`;

    let paragraphs: Para[];
    if (category.id === "love-life") paragraphs = loveLife(q, me, input.name ?? "", val.v, ledger, qi);
    else if (category.id === "love-compatibility" && pt) paragraphs = compat(q, me, pt, input.name ?? "", input.partnerName ?? "", val.v, ledger, qi, ledgerP);
    else if (category.id === "love-reunion" && pt) paragraphs = reunion(q, me, pt, input.name ?? "", input.partnerName ?? "", val.v, ledger, qi, ledgerP);
    else if (category.id === "life-overview") paragraphs = lifeOverview(q, me, input.name ?? "", val.v, ledger, qi);
    else paragraphs = light(category, q, me, val.v, ledger, qi);

    return { question: q, headline, gauge: val.gauge, content: joinParas(paragraphs) };
  });

  const extraAnswer =
    input.extraQuestion
      ? {
          q: input.extraQuestion,
          content: joinParas(answerParagraphs(me, pt, input.extraQuestion, TOPIC[category.id] ?? "이 흐름")),
        }
      : undefined;

  const closingAdvice = deterministicAdvice(ctx);

  return { category, freeSummary: category.previewLine, sections, closingAdvice, extraAnswer };
}

