/* 오행 상생/상극 관계 (연애 역학용) */
function relation(a: Element, b: Element): "生나→상대" | "生상대→나" | "剋나→상대" | "剋상대→나" | "比" {
  if ((a + 1) % 5 === b) return "生나→상대";
  if ((b + 1) % 5 === a) return "生상대→나";
  if ((a + 2) % 5 === b) return "剋나→상대";
  if ((b + 2) % 5 === a) return "剋상대→나";
  return "比";
}

