/** LIFE_EL.essence는 전부 "당신은 [수식어구]는/한/은 사람입니다."로 시작한다.
 *  그 수식어구만 뽑아 "~는 쪽/결" 같은 조사를 안전하게 이어붙이기 위한 헬퍼 —
 *  essence.split(".")[0]를 그대로 이어붙이면 "...사람입니다는"처럼 문장이 깨진다. */
function essenceCore(le: LifeEl): string {
  // 비탐욕(non-greedy) 매칭 — essence 뒷부분에도 "사람입니다"가 또 나올 수 있어서,
  // 탐욕적으로 매칭하면 첫 문장을 훌쩍 넘어 문장 전체를 삼켜버린다.
  return le.essence.match(/^당신은 (.+?) 사람입니다/)?.[1] ?? le.essence.split(".")[0];
}

