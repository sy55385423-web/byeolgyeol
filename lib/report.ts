function flow(c: Chart, salt: number, topic: string) {
  const good = 1 + ((c.seed + salt * 5) % 12);
  const risk = 1 + ((c.seed + 7 + salt * 3) % 12);
  const lines = [
    `이 부분이 크게 움직이는 시기는 ${good}월 전후입니다. 이때 들어오는 신호는 평소보다 진짜일 확률이 높으니 흘려보내지 않는 게 좋습니다. 반대로 ${risk}월 전후는 감정이 앞서 판단이 흐려지기 쉬운 구간이라, 이 시기의 큰 결정은 2주만 미뤄도 결과가 달라집니다.`,
    `흐름상 ${good}월 무렵에 변화의 창이 열립니다. 다만 ${risk}월에는 같은 상황도 더 예민하게 받아들이기 쉬우니, 이때 내린 결론은 한 박자 뒤에 다시 확인하세요.`,
    `${good}월 전후로 흐름이 당신 쪽으로 기웁니다. 반면 ${risk}월은 조급함이 실수를 부르는 시기라, 먼저 움직이기보다 상대의 반응을 보고 맞추는 편이 안전합니다.`,
  ];
  return pick(lines, c.seed + salt);
}

