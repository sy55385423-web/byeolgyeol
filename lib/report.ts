/** 조사 helper — 한자·괄호 등 비한글 꼬리는 건너뛰고 마지막 한글 음절의 받침으로 판정 */
function lastJong(word: string): number {
  for (let i = word.length - 1; i >= 0; i--) {
    const c = word.charCodeAt(i);
    if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28;
  }
  return -1; // 한글 없음
}
