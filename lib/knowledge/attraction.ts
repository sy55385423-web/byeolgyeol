/** 십신 → 갈래. analyze의 godGroup과 같은 분류를 규칙 쪽에서도 쓴다. */
function godGroupOf(g: string) {
  if (g === "비견" || g === "겁재") return "비겁";
  if (g === "식신" || g === "상관") return "식상";
  if (g === "편재" || g === "정재") return "재성";
  if (g === "편관" || g === "정관") return "관성";
  if (g === "편인" || g === "정인") return "인성";
  return "";
}
